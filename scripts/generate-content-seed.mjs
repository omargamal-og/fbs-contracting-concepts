const slugify = (value) => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase()
export function seedId(key) {
  const hex = createHash('sha256').update('fbs-corporate-v2:' + key).digest('hex').slice(0,32)
  return [hex.slice(0,8),hex.slice(8,12),'5' + hex.slice(13,16),'a' + hex.slice(17,20),hex.slice(20)].join('-')
}
// Parse literal data only: never execute TSX or import image modules.
export function readSourceLiteral(relativePath, variable) {
  const source = ts.createSourceFile(relativePath, fs.readFileSync(path.join(root,relativePath),'utf8'),ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX)
  const imports = new Map()
  for (const node of source.statements) {
    if (ts.isImportDeclaration(node) && node.importClause?.name && ts.isStringLiteral(node.moduleSpecifier)) {
      imports.set(node.importClause.name.text,path.posix.normalize(path.posix.join(path.posix.dirname(relativePath),node.moduleSpecifier.text)))
    }
  }
  function literal(node) {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text
    if (ts.isNumericLiteral(node)) return Number(node.text)
    if (node.kind === ts.SyntaxKind.TrueKeyword) return true
    if (node.kind === ts.SyntaxKind.FalseKeyword) return false
    if (node.kind === ts.SyntaxKind.NullKeyword) return null
    if (ts.isIdentifier(node) && imports.has(node.text)) return imports.get(node.text)
    if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal)
    if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map(property => {
      if (!ts.isPropertyAssignment(property)) throw new Error('Non-literal property in ' + relativePath)
      return [property.name.text,literal(property.initializer)]
    }))
    throw new Error('Non-literal source data in ' + relativePath + ': ' + node.getText(source))
  }
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue
    for (const declaration of statement.declarationList.declarations) {
      if (declaration.name.getText(source) === variable && declaration.initializer) return literal(declaration.initializer)
    }
  }
  throw new Error('Missing source variable: ' + variable)
}
const sqlValue = value => value === null || value === undefined ? 'null' : typeof value === 'boolean' || typeof value === 'number' ? String(value) : "'" + (typeof value === 'object' ? JSON.stringify(value) : value).replaceAll("'","''") + "'"
export function buildSeed() {
  const dictionaries = Object.fromEntries(['en','ar'].map(language => [language,readSourceLiteral('src/contracting/site/i18n/' + language + '.ts',language)]))
  const projects = readSourceLiteral(sourceFiles[0],'projects')
  const statistics = readSourceLiteral(sourceFiles[4],'statistics')
  const navigation = readSourceLiteral(sourceFiles[1],'mainNavigation')
  if (projects.length !== 8 || statistics.length !== 7) throw new Error('Source inventory changed; review the import explicitly.')
  const lines = ['-- Generated by npm run content:seed. Corporate sources only; ALL records are unapproved drafts.', '-- Re-running never overwrites existing editorial records. No users, roles, applications, or objects are seeded.', 'begin;']
  const counts = {}
  const assets = []
  const insert = (table, row) => {
    const keys = 'id' in row ? ['id'] : 'language_code' in row ? ['content_id','language_code'] : ['content_id']
    const predicate = keys.map(key => key + ' = ' + sqlValue(row[key])).join(' and ')
    lines.push('insert into ' + table + ' (' + Object.keys(row).join(',') + ') select ' + Object.values(row).map(sqlValue).join(',') + ' where not exists (select 1 from ' + table + ' where ' + predicate + ') on conflict do nothing;')
  }
  function item(kind,slug,table,details,translations,source,sourcePage = null,order = 0,sourceSnapshot = null) {
    const id = seedId(kind + ':' + slug)
    counts[kind] = (counts[kind] || 0) + 1
    insert('public.content_items',{id,kind,slug,publication_status:'draft',approval_status:'unreviewed',sort_order:order})
    insert('public.' + table,{id,...details})
    for (const language of ['en','ar']) insert('public.content_translations',{content_id:id,language_code:language,...translations[language]})
    insert('private.content_provenance',{content_id:id,source_reference:source,source_snapshot:sourceSnapshot,source_page:sourcePage,import_key:'corporate-v2:' + kind + ':' + slug,notes:'Imported from the existing repository. Source document/version and business approval must be verified.'})
    return id
  }
  const localized = get => Object.fromEntries(['en','ar'].map(language => [language,get(dictionaries[language],language)]))
  item('site_settings','corporate-settings','site_settings',{contact_email:'info.cont@fbs.com.sa',contact_phone:'920024010'},localized(d => ({title:d.navigation.logo_t1 + ' ' + d.navigation.logo_t2,content:{footer:d.footer,language:d.language}})), 'src/contracting/site/i18n/{en,ar}.ts; src/contracting/site/pages/contact/ContactPage.tsx',null,0,dictionaries)
  const pageIds = new Map()
  const homeId = item('page','home','pages',{route_path:''},localized(d => ({title:d.navigation.home,content:d.home})),sourceFiles[2])
  pageIds.set('',homeId)
  const routes = [
    ['about/who-we-are','about','whoWeAre'], ['about/chairman-speech','about','chairmanSpeech'], ['about/ceo-message','about','ceoSpeech'],
    ['about/why-fbs-contracting','about','whyFbs'], ['about/our-team','about','ourTeam'], ['about/vision-mission','about','visionMission'],
    ['about/saudi-vision-2030','about','saudiVision2030'], ['about/core-values','about','coreValues'],
    ['sustainability/environmental-responsibility','sustainability','environmental'], ['sustainability/social-responsibility','sustainability','social'],
    ['sustainability/economic-responsibility','sustainability','economic'], ['sustainability/continuous-improvement','sustainability','continuousImprovement'],
    ['business-continuity/risk-assessment-management','businessContinuity','riskAssessment'], ['business-continuity/business-impact-analysis','businessContinuity','businessImpactAnalysis'],
    ['business-continuity/plan-development','businessContinuity','planDevelopment'], ['business-continuity/recovery-restoration','businessContinuity','recoveryRestoration'],
    ['business-continuity/leadership-accountability','businessContinuity','leadershipAccountability'],
    ['careers','careers'], ['training','training'], ['suppliers','supplierRegistration'], ['contact','contact'],
  ]
  for (const [route,group,key] of routes) {
    const getContent = d => key ? d.innerPages[group][key] : d.innerPages[group]
    pageIds.set(route,item('page',route.replaceAll('/','-'),'pages',{route_path:route},localized(d => ({title:getContent(d).title,content:getContent(d)})),'src/contracting/site/i18n/{en,ar}.ts#innerPages.' + group + (key ? '.' + key : '')))
  }
  const sectionTypes = {hero:'hero',companyIntroduction:'introduction',capabilities:'services',projectCategories:'sectors',projectMap:'map',vision2030:'editorial',values:'editorial',sustainability:'editorial',contactCta:'contact'}
  Object.entries(sectionTypes).forEach(([key,type],order) => item('page_section','home-' + slugify(key),'page_sections',{page_id:homeId,section_key:key,section_type:type},localized(d => {
    const section = d.home[key]
    return {title:[section.titleLine1,section.titleLine2].filter(Boolean).join(' '),summary:section.description || null,content:section}
  }),'src/contracting/site/i18n/{en,ar}.ts#home.' + key,null,order))
  const sectorIds = new Map()
  for (const key of ['residential','commercial']) {
    sectorIds.set(key,item('sector',key,'sectors',{},localized(d => ({title:d.home.projectCategories[key].title,summary:d.home.projectCategories[key].description})),'src/contracting/site/i18n/{en,ar}.ts#home.projectCategories'))
    pageIds.set('projects/' + key,item('page','projects-' + key,'pages',{route_path:'projects/' + key},localized(d => ({title:d.home.projectCategories[key].title,summary:d.home.projectCategories[key].description})),'src/contracting/site/i18n/{en,ar}.ts#home.projectCategories'))
  }
  dictionaries.en.home.capabilities.items.forEach((name,index) => item('service',slugify(name),'services',{},localized(d => ({title:d.home.capabilities.items[index]})),'src/contracting/site/i18n/{en,ar}.ts#home.capabilities.items',null,index))
  function imageAsset(relativePath,slug,translations) {
    if (!fs.existsSync(path.join(root,relativePath))) throw new Error('Missing source asset: ' + relativePath)
    assets.push({slug,sourcePath:relativePath,uploadStatus:'not_uploaded',approvalStatus:'unreviewed'})
    return item('media_asset',slug,'media_assets',{media_type:'image',object_path:null},translations,relativePath)
  }
  for (const [order,project] of projects.entries()) {
    const translation = Object.fromEntries(['en','ar'].map(language => [language,{title:project.name[language],location_label:project.location[language]}]))
    const id = item('project',project.slug,'projects',{
      sector_id:sectorIds.get(project.category),city_key:project.region,delivery_status:'unspecified',
      start_year:project.constructionPeriod?.startYear ?? null,end_year:project.constructionPeriod?.endYear ?? null,
      units_count:project.units?.count ?? null,units_type:project.units?.type ?? null,
      latitude:null,longitude:null,coordinates_verified:false,location_precision:'unknown',
    },translation,sourceFiles[0] + '; company profile page reference (document unavailable)',project.sourcePage,order)
    const assetId = imageAsset(project.image,project.slug + '-cover',translation)
    item('project_media',project.slug + '-cover','project_media',{project_id:id,asset_id:assetId,media_role:'cover'},translation,sourceFiles[0],project.sourcePage)
  }
  for (const [order,stat] of statistics.entries()) item('statistic',slugify(stat.id),'statistics',{
    value:stat.value,unit:stat.unit ?? null,qualifier:stat.plus ? 'plus' : 'exact',display_divisor:stat.divisor ?? 1,reference_date:null,
  },localized(d => ({title:d.home.hero.statistics.labels[stat.id],content:{approvalNotice:d.home.hero.statistics.approvalNotice}})),sourceFiles[4] + '; src/contracting/site/assets/images/home/hero-projects.jpg',null,order)
  const heroTranslations = localized(d => ({title:d.home.hero.eyebrow,alt_text:d.home.hero.imageAlt}))
  const heroAsset = imageAsset('src/contracting/site/assets/images/home/fbs-hero-architecture.webp','existing-home-hero',heroTranslations)
  item('hero_media','existing-home-image','hero_media',{page_id:homeId,asset_id:heroAsset},heroTranslations,'src/contracting/site/components/home/HomeHero.tsx')
  for (const [order,nav] of navigation.entries()) {
    const parentId = item('navigation_item',slugify(nav.labelKey),'navigation_items',{page_id:pageIds.get(nav.path) ?? null},localized(d => ({title:d.navigation[nav.labelKey]})),sourceFiles[1],null,order)
    for (const [childOrder,child] of (nav.children || []).entries()) item('navigation_item',slugify(child.labelKey),'navigation_items',{parent_id:parentId,page_id:pageIds.get(child.path) ?? null},localized(d => ({title:d.navigation[child.labelKey]})),sourceFiles[1],null,childOrder)
  }
  lines.push('commit;','')
  return {
    sql:lines.join('\n'),
    manifest:{sourceHashes:Object.fromEntries(sourceFiles.map(file => [file,createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')])),counts,projectSlugs:projects.map(p => p.slug),unapprovedStatistics:statistics.map(s => s.id),assets},
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = buildSeed()
  const files = {'supabase/seed.sql':result.sql,'supabase/seed-manifest.json':JSON.stringify(result.manifest,null,2) + '\n'}
  for (const [file,content] of Object.entries(files)) {
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(path.join(root,file)) || fs.readFileSync(path.join(root,file),'utf8') !== content) throw new Error('Stale generated import: ' + file + '. Run npm run content:seed.')
    } else fs.writeFileSync(path.join(root,file),content)
  }
  console.log(process.argv.includes('--check') ? 'Corporate draft seed matches source files.' : 'Generated corporate drafts; no database connection or media upload performed.')
}
